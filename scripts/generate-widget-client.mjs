import {mkdir,writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'vite';

const root=fileURLToPath(new URL('../',import.meta.url));
const outputDirectory=resolve(root,'node_modules/.cache/action-tools');
const entry=resolve(root,'lib/ui/client.ts');
const result=await build({
 configFile:false,
 root,
 logLevel:'error',
 build:{
  write:false,
  emptyOutDir:false,
  minify:true,
  target:'es2022',
  lib:{entry,name:'WidgetClient',formats:['iife'],fileName:'widget-client'},
 },
});
const outputs=Array.isArray(result)?result.flatMap(item=>item.output):result.output;
const bundles=outputs.filter(item=>item.type==='chunk');
if(bundles.length!==1)throw new Error(`Expected one self-contained UI client bundle, received ${bundles.length}.`);
const source=bundles[0].code;
if(/\bimport\s*\(/.test(source)||/\bfrom\s*["']/.test(source))throw new Error('The UI client bundle must not require external modules.');
await mkdir(outputDirectory,{recursive:true});
await writeFile(resolve(outputDirectory,'widget-client.generated.ts'),`// Generated by scripts/generate-widget-client.mjs. Do not edit.\nexport const widgetClientSource=${JSON.stringify(source)};\n`);
